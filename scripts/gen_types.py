"""Generate packages/types/src/models.gen.ts from server/pulselens/models.py.

models.py is the source of truth (CLAUDE.md). Run `make types` after changing it; test_types_mirror.py
fails while the TypeScript file is stale. Handles the JSON-schema shapes the models use: primitives,
Literal enums, nullable unions, lists and string-keyed dicts.
"""

from __future__ import annotations

import json
import sys
import typing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "packages/types/src/models.gen.ts"
sys.path.insert(0, str(ROOT / "server"))

from pulselens import models  # noqa: E402

PRIMITIVES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def literal_names() -> dict[tuple[str, ...], str]:
    return {tuple(typing.get_args(t)): name for name, t in models.LITERAL_ALIASES.items()}


def ts_type(s: dict[str, Any], aliases: dict[tuple[str, ...], str]) -> str:
    if "anyOf" in s:
        parts = [ts_type(p, aliases) for p in s["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in s:
        values = tuple(s["enum"])
        return aliases.get(values) or " | ".join(f'"{v}"' for v in values)
    if "const" in s:
        return aliases.get((s["const"],)) or f'"{s["const"]}"'
    t = s.get("type")
    if t == "array":
        inner = ts_type(s.get("items", {}), aliases)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        extra = s.get("additionalProperties", True)
        value = "unknown" if extra in (True, {}) else ts_type(extra, aliases)
        return f"Record<string, {value}>"
    if t in PRIMITIVES:
        return PRIMITIVES[t]
    return "unknown"


def render() -> str:
    aliases = literal_names()
    out = [
        "// GENERATED by scripts/gen_types.py from server/pulselens/models.py. Do not edit; run `make types`.",
        "",
    ]
    for name, lit in models.LITERAL_ALIASES.items():
        values = typing.get_args(lit)
        const = name[0].lower() + name[1:]
        out.append(f"export const {const}Values = {json.dumps(list(values))} as const;")
        out.append(f"export type {name} = (typeof {const}Values)[number];")
        out.append("")
    for model in models.EXPORTED_MODELS:
        schema = model.model_json_schema(mode="serialization")
        required = set(schema.get("required", []))
        if model.__doc__ and model.__module__ == models.__name__ and "\n" not in model.__doc__.strip():
            out.append(f"/** {model.__doc__.strip()} */")
        out.append(f"export interface {model.__name__} {{")
        for field, prop in schema["properties"].items():
            if "description" in prop:
                out.append(f"  /** {prop['description']} */")
            optional = "" if field in required else "?"
            out.append(f"  {field}{optional}: {ts_type(prop, aliases)};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
